"""Writes the small picker as C for Joshua Tree: picker_weights.h (sparse int16 weights) and picker_golden.h
(sentences with the Python reference's pick, so the kernel proves parity). Usage: export_c.py WEIGHTS.json OUT_DIR"""
import json, sys, os
sys.path.insert(0, os.path.dirname(__file__))
import ref

d = json.load(open(sys.argv[1])); out = sys.argv[2]
W, bias, tools = d["W"], d["bias"], d["tools"]
ent = [[] for _ in range(ref.B)]
for h, row in enumerate(W):
    for k, w in enumerate(row):
        if w: ent[h].append((k, w))
off, flat = [0], []
for e in ent:
    flat += e; off.append(len(flat))
with open(out + "/picker_weights.h", "w") as f:
    f.write("/* Generated by turing training/smallpicker/export_c.py from the integer weights. Do not edit. */\n")
    f.write(f"#define PICK_B {ref.B}\n#define PICK_K {len(tools)}\n#define PICK_N {len(flat)}\n#define PICK_MARGIN {ref.MARGIN}\n#define PICK_NULL {tools.index(ref.OOS)}\n")
    f.write("static const char *const pick_tools[PICK_K] = {" + ",".join(json.dumps(t) for t in tools) + "};\n")
    f.write(f"static const short pick_bias[PICK_K] = {{{','.join(map(str, bias))}}};\n")
    f.write(f"static const unsigned short pick_off[PICK_B + 1] = {{{','.join(map(str, off))}}};\n")
    f.write(f"static const unsigned char pick_cls[PICK_N] = {{{','.join(str(k) for k, _ in flat)}}};\n")
    f.write(f"static const signed char pick_w[PICK_N] = {{{','.join(str(w) for _, w in flat)}}};\n")
rows = []
for n in ["", "2", "3", "5", "6", "8", "9", "10", "11"]:
    rows += [json.loads(l)["text"] for l in open(f"eval/heldout{n}.jsonl")]
rows = [t for t in rows if t.isascii() and '"' not in t and "\\" not in t and len(t) < 120][::15]
with open(out + "/picker_golden.h", "w") as f:
    f.write("/* Generated by turing training/smallpicker/export_c.py: sentences and the Python reference's pick. Do not edit. */\n")
    f.write(f"#define PICK_GOLDEN_N {len(rows)}\nstatic const struct {{ const char *text; unsigned char want; }} pick_golden[PICK_GOLDEN_N] = {{\n")
    for t in rows:
        f.write(f'    {{"{t}", {tools.index(ref.pick(W, bias, tools, t))}}},\n')
    f.write("};\n")
print(len(flat), "weights,", len(rows), "golden sentences")

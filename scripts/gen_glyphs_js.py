"""Writes web/glyphs.js from app/tools_glyphs.py, so the landing demo draws the same glyph logos she does and the two never drift.
Run with --check to fail when the file is stale (the test suite does)."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "app"))
import tools_glyphs  # noqa: E402

OUT = os.path.join(ROOT, "web", "glyphs.js")


def build():
    """The text of web/glyphs.js: palettes, and each glyph's keyword pattern and layers."""
    data = {"palettes": tools_glyphs.GLYPH_PALETTES, "glyphs": {n: {"words": w, "layers": l} for n, (w, l) in tools_glyphs.GLYPHS.items()}}
    return ("// Generated by scripts/gen_glyphs_js.py from app/tools_glyphs.py. Do not edit.\n"
            "window.SAMANTHA_GLYPHS = " + json.dumps(data, indent=1, ensure_ascii=True) + ";\n")


def main():
    """Write the file, or with --check say whether it is current."""
    text = build()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        print("web/glyphs.js is current" if current == text else "web/glyphs.js is stale: run python3 scripts/gen_glyphs_js.py")
        sys.exit(0 if current == text else 1)
    with open(OUT, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
